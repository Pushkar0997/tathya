#!/usr/bin/env python3
"""fetch_fonts: download self-hosted SIL OFL woff2 font files listed in design/tokens.json (M2-FNT-01).

Run locally on a machine with internet access to populate static/fonts/*.woff2 and
generate static/css/fonts.css with @font-face rules and font-display: swap.
Built pages load ONLY local static/fonts/*.woff2 files (zero third-party requests, INV-7).

Standard library only.
"""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS_DIR = ROOT / "static" / "fonts"
FONTS_CSS = ROOT / "static" / "css" / "fonts.css"

GOOGLE_CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Abril+Fatface&"
    "family=Caveat:wght@600&"
    "family=DM+Sans:wght@400;500;700&"
    "family=Fraunces:ital,wght@0,900;1,900&"
    "family=Great+Vibes&"
    "family=Instrument+Serif:ital@1&"
    "family=Pinyon+Script&"
    "family=Playfair+Display:ital,wght@0,400;0,700;0,900;1,400;1,700;1,900&"
    "family=Rozha+One&"
    "family=Syne:wght@800&"
    "display=swap"
)

# Modern Chromium User-Agent so Google Fonts returns woff2 format
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
    "AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/130.0.0.0 Safari/537.36"
)


def fetch_bytes(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def main() -> int:
    FONTS_DIR.mkdir(parents=True, exist_ok=True)
    FONTS_CSS.parent.mkdir(parents=True, exist_ok=True)

    print("Fetching Google Fonts CSS descriptor...")
    css_text = fetch_bytes(GOOGLE_CSS_URL).decode("utf-8")

    # Keep only latin subsets for all fonts, plus devanagari for Rozha One
    blocks = re.findall(r"/\*\s*([^*]+?)\s*\*/\s*@font-face\s*\{([^}]+)\}", css_text, re.S)
    if not blocks:
        print("error: could not parse @font-face blocks from Google Fonts CSS", file=sys.stderr)
        return 1

    out_blocks: list[str] = [
        "/* Self-hosted SIL OFL woff2 fonts generated by scripts/fetch_fonts.py. Zero external requests (INV-7). */",
        "",
    ]
    downloaded: dict[str, str] = {}
    count = 0

    for subset_raw, body in blocks:
        subset = subset_raw.strip().lower()
        fam_m = re.search(r"font-family:\s*'([^']+)'", body)
        wt_m = re.search(r"font-weight:\s*(\d+)", body)
        st_m = re.search(r"font-style:\s*(\w+)", body)
        url_m = re.search(r"url\((https://[^)]+\.woff2)\)", body)
        if not (fam_m and url_m):
            continue

        family = fam_m.group(1)
        weight = wt_m.group(1) if wt_m else "400"
        style = st_m.group(1) if st_m else "normal"
        remote_url = url_m.group(1)

        allowed_subsets = {"latin", "devanagari"} if family == "Rozha One" else {"latin"}
        if subset not in allowed_subsets:
            continue

        slug = re.sub(r"[^a-z0-9]+", "-", family.lower()).strip("-")
        filename = f"{slug}-{weight}-{style}-{subset}.woff2"
        if remote_url not in downloaded:
            print(f"Downloading {filename}...")
            data = fetch_bytes(remote_url)
            (FONTS_DIR / filename).write_bytes(data)
            downloaded[remote_url] = filename
            count += 1
        else:
            filename = downloaded[remote_url]

        local_body = re.sub(
            r"url\(https://[^)]+\.woff2\)",
            f"url('../fonts/{filename}')",
            body.strip(),
        )
        out_blocks.append(f"/* {family} ({subset}) */")
        out_blocks.append("@font-face {")
        out_blocks.append(f"  {local_body}")
        out_blocks.append("}")
        out_blocks.append("")

    FONTS_CSS.write_text("\n".join(out_blocks), encoding="utf-8")
    print(f"Done: downloaded {count} woff2 file(s) into static/fonts/ and wrote static/css/fonts.css")
    return 0


if __name__ == "__main__":
    sys.exit(main())
