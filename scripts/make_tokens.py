#!/usr/bin/env python3
"""make_tokens: generate static/css/tokens.css from design/tokens.json (M2-CSS-01, G-25).

Standard library only. Defines every shared and area-scoped colour, font, type scale,
layout, and sticker token as CSS custom properties, scoped per area with a class on body.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _kebab(name: str) -> str:
    return name.replace("_", "-")


def _font_stack(font_obj: dict) -> str:
    family = font_obj["family"]
    fallback = font_obj.get("fallback", "sans-serif")
    return f"'{family}', {fallback}"


def generate_tokens_css(tokens_path: Path | None = None, out_path: Path | None = None) -> str:
    src = tokens_path or (ROOT / "design" / "tokens.json")
    dst = out_path or (ROOT / "static" / "css" / "tokens.css")

    data = json.loads(src.read_text(encoding="utf-8"))
    shared = data["shared"]
    areas = data["areas"]

    lines: list[str] = [
        "/* Generated by scripts/make_tokens.py from design/tokens.json. Do not edit by hand. */",
        ":root, body, body.area-shared {",
    ]

    # Shared colors
    for key, val in shared["colors"].items():
        k = _kebab(key)
        lines.append(f"  --shared-color-{k}: {val};")
        lines.append(f"  --color-{k}: {val};")

    # Default semantic surface colors for shared pages (home, contribute, about)
    sc = shared["colors"]
    lines.append(f"  --color-hero-bg: {sc['indigo']};")
    lines.append(f"  --color-hero-fg: {sc['lilac']};")
    lines.append(f"  --color-heading-on-hero: {sc['white']};")
    lines.append(f"  --color-accent: {sc['marigold']};")
    lines.append(f"  --color-ink: {sc['indigo']};")
    lines.append(f"  --color-rule: {sc['lilac']};")
    lines.append(f"  --color-sticker-bg: {sc['rani']};")
    lines.append(f"  --color-sticker-fg: {sc['white']};")
    lines.append(f"  --color-tag-bg: {sc['marigold']};")
    lines.append(f"  --color-tag-fg: {sc['indigo']};")
    lines.append(f"  --color-card-bar: {sc['rani']};")

    # Shared fonts
    for key, fobj in shared["fonts"].items():
        k = _kebab(key)
        stack = _font_stack(fobj)
        weights = ",".join(str(w) for w in fobj.get("weights", [400]))
        styles = ",".join(fobj.get("styles", ["normal"]))
        lines.append(f"  --shared-font-{k}: {stack};")
        lines.append(f"  --font-{k}: {stack};")
        lines.append(f"  --font-{k}-weights: {weights};")
        lines.append(f"  --font-{k}-styles: {styles};")

    lines.append(f"  --font-display: {_font_stack(shared['fonts']['home_display'])};")
    lines.append("  --font-display-weight: 900;")
    lines.append("  --font-display-style: normal;")
    lines.append(f"  --font-script: {_font_stack(shared['fonts']['home_script'])};")
    lines.append("  --font-script-weight: 400;")
    lines.append("  --font-script-style: normal;")

    # Shared sticker tokens
    for key, val in shared["sticker"].items():
        k = _kebab(key)
        if isinstance(val, (int, float)) and "deg" in key:
            lines.append(f"  --sticker-{k}: {val}deg;")
        elif isinstance(val, (int, float)) and "px" in key:
            lines.append(f"  --sticker-{k}: {val}px;")
        elif isinstance(val, str):
            lines.append(f'  --sticker-{k}: "{val}";')
        else:
            lines.append(f"  --sticker-{k}: {val};")

    # Shared type scale tokens
    for key, val in shared["type_scale"].items():
        k = _kebab(key)
        lines.append(f"  --type-{k}: {val};")

    # Shared layout tokens
    for key, val in shared["layout"].items():
        k = _kebab(key)
        if isinstance(val, (int, float)) and "px" in key:
            lines.append(f"  --layout-{k}: {val}px;")
        else:
            lines.append(f"  --layout-{k}: {val};")

    # Expose area-prefixed tokens on :root as well for home page area tiles
    for area_id, aobj in areas.items():
        for ckey, cval in aobj["colors"].items():
            lines.append(f"  --{area_id}-color-{_kebab(ckey)}: {cval};")
        for fkey, fobj in aobj["fonts"].items():
            lines.append(f"  --{area_id}-font-{_kebab(fkey)}: {_font_stack(fobj)};")

    lines.append("}")
    lines.append("")

    # Scoped per-area classes on body
    for area_id, aobj in areas.items():
        lines.append(f"body.area-{area_id} {{")
        for ckey, cval in aobj["colors"].items():
            k = _kebab(ckey)
            lines.append(f"  --color-{k}: {cval};")
        disp = aobj["fonts"]["display"]
        scr = aobj["fonts"]["script"]
        disp_w = disp.get("weights", [700])[0]
        disp_s = disp.get("styles", ["normal"])[0]
        scr_w = scr.get("weights", [400])[0]
        scr_s = scr.get("styles", ["normal"])[0]
        lines.append(f"  --font-display: {_font_stack(disp)};")
        lines.append(f"  --font-display-weight: {disp_w};")
        lines.append(f"  --font-display-style: {disp_s};")
        lines.append(f"  --font-script: {_font_stack(scr)};")
        lines.append(f"  --font-script-weight: {scr_w};")
        lines.append(f"  --font-script-style: {scr_s};")
        lines.append("}")
        lines.append("")

    css_text = "\n".join(lines)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(css_text, encoding="utf-8")
    return css_text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tokens", default=None, help="path to design/tokens.json")
    parser.add_argument("--out", default=None, help="output CSS file path (default: static/css/tokens.css)")
    args = parser.parse_args(argv)

    t_path = Path(args.tokens) if args.tokens else None
    o_path = Path(args.out) if args.out else None
    generate_tokens_css(t_path, o_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
